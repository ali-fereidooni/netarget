package fingerprint

import (
	"net/netip"
	"strings"
	"testing"
)

func sigs(t *testing.T) []Signature {
	t.Helper()
	s, err := Signatures()
	if err != nil {
		t.Fatal(err)
	}
	return s
}

func hdr(kv ...string) map[string][]string {
	m := map[string][]string{}
	for i := 0; i+1 < len(kv); i += 2 {
		m[strings.ToLower(kv[i])] = append(m[strings.ToLower(kv[i])], kv[i+1])
	}
	return m
}

func TestEmbeddedSignaturesValid(t *testing.T) {
	s := sigs(t)
	kinds := map[string]int{}
	for _, x := range s {
		kinds[x.Kind]++
	}
	// Every CDN and server the spec names must be present.
	need := []string{"cloudflare", "cloudfront", "akamai", "fastly", "sucuri", "imperva", "bunny", "google-cdn",
		"azure-frontdoor", "nginx", "apache", "litespeed", "iis", "caddy", "wordpress", "laravel", "nextjs"}
	have := map[string]bool{}
	for _, x := range s {
		have[x.ID] = true
	}
	for _, n := range need {
		if !have[n] {
			t.Errorf("missing signature %s", n)
		}
	}
}

func TestDetectCloudflareInFrontOfNginx(t *testing.T) {
	in := Input{Samples: []Sample{
		{Source: "GET https://example.com/", Status: 200, Headers: hdr("Server", "cloudflare", "CF-RAY", "8a1b2c3d4e5f-FRA", "cf-cache-status", "DYNAMIC"),
			Cookies: []string{"__cf_bm"}, Body: `<html><link href="/wp-content/themes/x.css"></html>`},
		{Source: "GET https://origin/ (origin direct)", Status: 404, Headers: hdr("Server", "nginx/1.24.0"), Body: "<center>nginx/1.24.0</center>"},
	}, IPs: []netip.Addr{netip.MustParseAddr("104.21.3.4")}}
	r := Detect(sigs(t), in)
	cdn := r.Primary("cdn")
	if cdn == nil || cdn.ID != "cloudflare" || cdn.Level != "high" || len(cdn.Evidence) < 3 {
		t.Fatalf("cdn %+v", r.CDN)
	}
	if s := r.Primary("server"); s == nil || s.ID != "nginx" || s.Level != "high" {
		t.Fatalf("server %+v", r.Server)
	}
	if p := r.Primary("platform"); p == nil || p.ID != "wordpress" {
		t.Fatalf("platform %+v", r.Platform)
	}
	if r.NoCDN {
		t.Fatal("NoCDN set")
	}
}

func TestSingleWeakSignalStaysLow(t *testing.T) {
	// "Via: 1.1 varnish" alone must not claim Fastly.
	r := Detect(sigs(t), Input{Samples: []Sample{{Source: "GET /", Headers: hdr("Via", "1.1 varnish")}}})
	if len(r.CDN) != 1 || r.CDN[0].ID != "fastly" || r.CDN[0].Level != "low" {
		t.Fatalf("%+v", r.CDN)
	}
	if !r.NoCDN || r.Primary("cdn") != nil {
		t.Fatal("a weak-only detection must not become the primary CDN")
	}
	// Two weak signals are still capped at low.
	r = Detect(sigs(t), Input{Samples: []Sample{{Source: "GET /", Headers: hdr("Server", "Google Frontend", "x-goog-hash", "crc32c=x")}}})
	if r.CDN[0].Level != "low" {
		t.Fatalf("weak-only reached %s", r.CDN[0].Level)
	}
}

func TestOneStrongSignalIsMediumNotHigh(t *testing.T) {
	r := Detect(sigs(t), Input{Samples: []Sample{{Source: "GET /", Headers: hdr("Server", "Apache/2.4.58 (Ubuntu)")}}})
	s := r.Primary("server")
	if s == nil || s.ID != "apache" || s.Level != "medium" {
		t.Fatalf("%+v", r.Server)
	}
}

func TestCNAMEAndBodySignals(t *testing.T) {
	r := Detect(sigs(t), Input{
		Samples: []Sample{{Source: "GET /", Status: 502, Body: "<H2>Generated by cloudfront (CloudFront)</H2>"}},
		CNAMEs:  []string{"d111111abcdef8.cloudfront.net."},
	})
	if c := r.Primary("cdn"); c == nil || c.ID != "cloudfront" || c.Level != "high" {
		t.Fatalf("%+v", r.CDN)
	}
	r = Detect(sigs(t), Input{Samples: []Sample{{Source: "GET /", Status: 403,
		Body: "<address>Apache/2.4.41 (Ubuntu) Server at example.com Port 443</address>"}}})
	if s := r.Primary("server"); s == nil || s.ID != "apache" || s.Level != "high" {
		t.Fatalf("%+v", r.Server)
	}
}

func TestNoCDN(t *testing.T) {
	r := Detect(sigs(t), Input{Samples: []Sample{{Source: "GET /", Headers: hdr("Server", "LiteSpeed", "x-litespeed-cache", "hit")}},
		IPs: []netip.Addr{netip.MustParseAddr("5.6.7.8")}})
	if !r.NoCDN || r.Primary("server").ID != "litespeed" {
		t.Fatalf("%+v", r)
	}
}

func TestParseRejectsBadData(t *testing.T) {
	bad := []string{
		"- {id: x, kind: cdn, name: X, signals: [{type: header, weight: strong}]}",            // no name
		"- {id: x, kind: weird, name: X, signals: [{type: header, name: a, weight: strong}]}", // kind
		"- {id: x, kind: cdn, name: X, signals: [{type: body, regex: '(', weight: strong}]}",  // regex
		"- {id: x, kind: cdn, name: X, signals: [{type: header, name: a, weight: huge}]}",     // weight
		"- {id: x, kind: cdn, name: X, bogus: 1, signals: [{type: header, name: a, weight: strong}]}",
	}
	for _, b := range bad {
		if _, err := Parse([]byte(b)); err == nil {
			t.Errorf("accepted: %s", b)
		}
	}
}
